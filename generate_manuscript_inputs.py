"""
Assembles manuscript_inputs/ — a single flat folder (no subfolders, per the
journal's submission requirement that all LaTeX inputs sit at the project
root) containing every file revised_manuscript/main_reproducible.tex needs
besides the static template (class/style/bib files, which don't change):
  - All 20 auto-generated table snippets (generate_latex_tables.py)
  - constants.tex (generate_latex_constants.py)
  - Every figure referenced by \\includesvg{}/\\includegraphics{}

Workflow: after a pipeline run, copy the entire contents of manuscript_inputs/
into the Overleaf project root (alongside main_reproducible.tex), overwriting
existing files — this refreshes every number and every plot in one step.

Most figures are regenerated by generate_paper_results.py into their numbered
paper_results/NN_subdir/ folders every run, so those are preferred. A handful
are either (a) only produced when NOT running with --skip-imagery (they
require NAIP tile downloads), or (b) hand-made static diagrams the pipeline
never generates (e.g. the CAFO labeling flowchart). For both cases we fall
back to whatever copy is already sitting in revised_manuscript/ — the last
version anyone placed there — and print a warning so it's clear which figures
in a given manuscript_inputs/ bundle are not freshly regenerated.
"""
import re
import shutil
from pathlib import Path

MANUSCRIPT_INPUTS_DIR = Path("manuscript_inputs")
MAIN_TEX_PATH = Path("revised_manuscript") / "main_reproducible.tex"
FALLBACK_DIR = Path("revised_manuscript")

# Figures known to require --skip-imagery=False (NAIP/GCS tile downloads) or
# to be hand-made static diagrams never produced by the pipeline at all.
# These fall back to revised_manuscript/ without a "stale" warning being
# treated as an error — just a heads-up.
KNOWN_STATIC_OR_IMAGERY_DEPENDENT = {
    "annotation_prediction_examples_annotated.png",
    "baseline_model_example_plots.png",
    "cafo_labeling_flowchart.png",  # hand-made illustration, no pipeline generator
    "clustering_pipeline.svg",      # hand-made diagram, no pipeline generator
    "false_neg_missed_area.png",
    "fig_appendix_cluster_compare.png",
    "large_false_pos_ag_products.png",
    "pixel_level_p_r_IOU_curves.png",
    "small_false_pos_trucking.png",
    "true_pos_model_permitted.png",
}


def _figure_references(main_tex_path):
    """Every \\includesvg{}/\\includegraphics{} target in main_reproducible.tex,
    with the .svg extension restored for \\includesvg (which omits it)."""
    text = main_tex_path.read_text()
    refs = []
    for kind, name in re.findall(r"\\include(svg|graphics)(?:\[[^\]]*\])?\{([^}]*)\}", text):
        if kind == "svg" and not Path(name).suffix:
            name = name + ".svg"
        refs.append(name)
    return sorted(set(refs))


def copy_manuscript_figures(paper_results_dir=Path("paper_results")):
    """Copy every figure main_reproducible.tex references into
    manuscript_inputs/, preferring the freshest paper_results/ copy and
    falling back to revised_manuscript/ for imagery-dependent/static figures.
    """
    MANUSCRIPT_INPUTS_DIR.mkdir(parents=True, exist_ok=True)
    refs = _figure_references(MAIN_TEX_PATH)

    n_fresh, n_fallback, n_missing = 0, 0, 0
    fallback_names = []
    for name in refs:
        matches = list(paper_results_dir.glob(f"**/{name}"))
        if matches:
            shutil.copy(matches[0], MANUSCRIPT_INPUTS_DIR / name)
            n_fresh += 1
            continue

        fallback_path = FALLBACK_DIR / name
        if fallback_path.exists():
            shutil.copy(fallback_path, MANUSCRIPT_INPUTS_DIR / name)
            n_fallback += 1
            fallback_names.append(name)
            continue

        n_missing += 1
        print(f"    WARNING: figure '{name}' not found in {paper_results_dir}/ or "
              f"{FALLBACK_DIR}/ -- manuscript_inputs/ will be missing it.")

    print(f"  Copied {n_fresh} freshly-regenerated figures, {n_fallback} from "
          f"{FALLBACK_DIR}/ (imagery-dependent or static diagrams not covered "
          f"by this run), {n_missing} missing entirely.")
    if fallback_names:
        unexpected = sorted(set(fallback_names) - KNOWN_STATIC_OR_IMAGERY_DEPENDENT)
        print(f"    From fallback: {', '.join(fallback_names)}")
        if unexpected:
            print(
                f"    NOTE: {', '.join(unexpected)} fell back to {FALLBACK_DIR}/ "
                "but aren't on the known static/imagery-dependent list -- worth "
                "checking why they weren't found in paper_results/ this run."
            )
    return {"fresh": n_fresh, "fallback": n_fallback, "missing": n_missing}


def generate_manuscript_inputs(paths, subdirs):
    """Full manuscript_inputs/ assembly: tables + constants + figures.

    Tables and constants are generated directly into manuscript_inputs/ by
    generate_latex_tables.generate_all_tables() and
    generate_latex_constants.generate_all_constants() (both point at
    manuscript_inputs/ already) — this just triggers those plus the figure
    copy, so callers only need one entry point.
    """
    import generate_latex_tables as glt
    import generate_latex_constants as glc

    glt.generate_all_tables(paths, subdirs)
    glc.generate_all_constants(paths, subdirs)
    copy_manuscript_figures(paper_results_dir=Path("paper_results"))
    print(f"  manuscript_inputs/ ready -- copy its contents into the Overleaf "
          f"project root (alongside main_reproducible.tex) to refresh the manuscript.")
